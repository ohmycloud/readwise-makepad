// Custom annotation colour/favorite drafts, persistence and reader continuity.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawn, execFileSync } = require('node:child_process');
const { chromium } = require(process.env.READWISE_PLAYWRIGHT_MODULE || 'playwright-core');
const root = path.resolve(__dirname, '../..');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'readwise-colours-'));
const artifacts = path.join(root, 'target/web-qa/colours');
fs.mkdirSync(artifacts, { recursive: true });
const fixture = path.join(temp, '自定义配色.epub');
execFileSync('python3', [path.join(__dirname, 'fixture.py'), fixture]);
let server, browser, log = '';
const errors = [];
async function start() {
  return new Promise((resolve, reject) => {
    server = spawn(process.env.READWISE_WEB_BINARY || path.join(root, 'target/debug/readwise-web'), [], { cwd: root, env: { ...process.env, READWISE_WEB_BIND: '127.0.0.1:0', READWISE_WEB_DATA_DIR: path.join(temp, 'data') } });
    const timer = setTimeout(() => reject(new Error('startup timeout')), 25000);
    let startup = '';
    const receive = chunk => { log += chunk; startup += chunk; const match = startup.match(/ReadWise Web: (http:\/\/[^\s]+)\n/); if (match) { clearTimeout(timer); resolve(match[1]); } };
    server.stdout.on('data', receive); server.stderr.on('data', receive); server.on('error', reject);
  });
}
async function stop() {
  if (!server || server.exitCode !== null) return;
  await new Promise(resolve => { server.once('exit', resolve); server.kill('SIGINT'); });
}
async function run() {
  let base = await start();
  const executablePath = process.env.READWISE_CHROMIUM || (process.platform === 'darwin' ? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' : undefined);
  browser = await chromium.launch({ headless: true, ...(executablePath ? { executablePath } : {}) });
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  const ready = async () => { await page.locator('body[data-browser-ready="true"]').waitFor(); await page.waitForTimeout(100); };
  const preferences = () => page.request.get(`${base}/api/preferences`).then(r => r.json());
  const rootSettings = page.locator('[data-appearance]');
  const chip = index => rootSettings.locator(`[data-custom-colour="${index}"]`);
  const hex = rootSettings.locator('.colour-hex');
  const custom = ['#8B6948', '#FFE9A8', '#3F6F98', '#F6D6CC'];
  const preview = () => rootSettings.locator('#appearance-annotations [data-preview]').evaluate(node => ['--gloss-color','--gloss-background','--word-color','--word-background'].map(key => node.style.getPropertyValue(key)));
  const setHex = async (index, value) => { if (await chip(index).getAttribute('aria-expanded') !== 'true') await chip(index).click(); await hex.fill(value); };
  const save = () => rootSettings.locator('[data-save-appearance]').click();
  await page.goto(base); await ready();
  await page.locator('#book-upload').setInputFiles(fixture);
  await page.locator('#import-results [data-state="success"] a').waitFor({ timeout: 30000 });
  const readUrl = await page.locator('#import-results a').getAttribute('href');
  await page.goto(`${base}/settings`); await ready();
  assert.equal(await chip(0).locator('[data-empty="true"]').count(), 1);
  assert.equal(await rootSettings.locator('.inline-colour-picker').isVisible(), false);
  const defaults = await preferences();
  for (let i = 0; i < 4; i++) {
    await setHex(i, custom[i]);
    assert.equal((await preview())[i], custom[i]);
    assert.equal(await chip(i).locator('.colour-dot').getAttribute('data-empty'), 'false');
  }
  assert.deepEqual((await preferences()).custom_colors, defaults.custom_colors);
  await hex.fill('#XYZ'); await save();
  assert.equal(await hex.getAttribute('aria-invalid'), 'true');
  assert.deepEqual((await preferences()).custom_colors, defaults.custom_colors);
  await hex.fill(custom[3]);
  await rootSettings.locator('[data-recommend-colour="#CFE8D5"]').click();
  assert.equal((await preview())[3], '#CFE8D5');
  const plane = rootSettings.locator('.colour-plane');
  await plane.scrollIntoViewIfNeeded();
  const rect = await plane.boundingBox();
  await page.mouse.move(rect.x + rect.width * .3, rect.y + 30); await page.mouse.down();
  await page.mouse.move(rect.x + rect.width * .6, rect.y + 80, { steps: 8 }); await page.mouse.up();
  assert.notEqual((await preview())[3], '#CFE8D5');
  await plane.focus(); await page.keyboard.press('ArrowRight');
  assert.equal(await hex.inputValue(), (await preview())[3]);
  await rootSettings.locator('.colour-hue').fill('280');
  assert.equal(await hex.inputValue(), (await preview())[3]);
  await hex.fill(custom[3]);
  await rootSettings.locator('[data-favorite-toggle]').click();
  assert.equal(await rootSettings.locator('.favorite-scheme').count(), 1);
  assert.equal(await rootSettings.locator('[data-favorite-toggle]').getAttribute('aria-pressed'), 'true');
  await setHex(0, '#3D6D59');
  await rootSettings.locator('[data-favorite-toggle]').click();
  assert.equal(await rootSettings.locator('.favorite-scheme').count(), 2);
  await rootSettings.locator('.favorite-apply').first().click();
  assert.deepEqual(await preview(), custom);
  assert.equal(await rootSettings.locator('.favorite-scheme').count(), 2);
  await page.screenshot({ path: path.join(artifacts, 'global-favorites.png'), fullPage: true });
  assert.equal((await preferences()).favorites.length, 0);
  await page.route('**/api/preferences', route => route.request().method() === 'POST' ? route.fulfill({ status: 500, body: '模拟保存失败' }) : route.continue());
  await save();
  await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('模拟保存失败'));
  assert.deepEqual(await preview(), custom);
  assert.equal(await rootSettings.locator('.favorite-scheme').count(), 2);
  assert.equal((await preferences()).favorites.length, 0);
  await page.unroute('**/api/preferences');
  await save();
  await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('已保存'));
  const saved = await preferences();
  assert.deepEqual(saved.custom_colors, custom);
  assert.equal(saved.favorites.length, 2);
  await page.reload(); await ready();
  assert.deepEqual(await preview(), custom);
  assert.equal(await rootSettings.locator('.favorite-scheme').count(), 2);
  console.log('PASS: four custom slots, hex validation, recommended colours, real SV drag/keyboard/hue preview, multiple favorites and save/reload');

  await page.goto(`${base}${readUrl}`); await ready();
  // Use the trigger's target as the source of truth for the aA dialog.
  const settingsTrigger = page.locator('[data-open]').filter({ hasText: 'aA' });
  const trigger = await settingsTrigger.count() ? settingsTrigger.first() : page.locator('[data-open="appearance-dialog"], [data-open="settings-dialog"]').first();
  const dialogId = await trigger.getAttribute('data-open');
  const aA = page.locator(`#${dialogId}`);
  await trigger.click(); await rootSettings.locator('[data-settings-tab="annotations"]').click();
  await setHex(0, '#123456');
  await rootSettings.locator('[data-favorite-toggle]').click();
  await page.setViewportSize({ width: 320, height: 640 });
  await rootSettings.locator('.colour-hex').scrollIntoViewIfNeeded();
  const panelPortrait = await rootSettings.locator('.inline-colour-picker').boundingBox();
  assert(panelPortrait.x >= 0 && panelPortrait.x + panelPortrait.width <= 320);
  await page.screenshot({ path: path.join(artifacts, 'picker-320.png') });
  await page.setViewportSize({ width: 640, height: 320 });
  assert.equal(await hex.inputValue(), '#123456');
  await rootSettings.locator('.favorite-remove').last().scrollIntoViewIfNeeded();
  const modalRect = await aA.boundingBox();
  assert(modalRect.y >= 0 && modalRect.y + modalRect.height <= 320);
  await page.screenshot({ path: path.join(artifacts, 'favorites-640.png') });
  await page.keyboard.press('Escape');
  assert.deepEqual((await preferences()).custom_colors, saved.custom_colors);
  assert.equal((await preferences()).favorites.length, 2);
  await trigger.click();
  assert.equal(await rootSettings.locator('.favorite-scheme').count(), 2);
  await rootSettings.locator('.favorite-remove').last().click();
  assert.equal(await rootSettings.locator('.favorite-scheme').count(), 1);
  await page.keyboard.press('Escape');
  await trigger.click();
  assert.equal(await rootSettings.locator('.favorite-scheme').count(), 2);
  await rootSettings.locator('[data-reset-settings="annotations"]').click();
  assert.equal(await rootSettings.locator('[data-custom-colour] [data-empty="true"]').count(), 4);
  assert.equal(await rootSettings.locator('.favorite-scheme').count(), 2);
  await page.keyboard.press('Escape');
  console.log('PASS: narrow/short inline cards, rotation draft, cancel discards colour/favorite deletion, reset clears custom colours but keeps favorites');

  await page.setViewportSize({ width: 1280, height: 900 });
  const articleStyles = () => page.locator('#reading-content').evaluate(node => ['--gloss-color','--gloss-background','--word-color','--word-background'].map(key => node.style.getPropertyValue(key)));
  const geometry = () => page.evaluate(() => [...document.querySelectorAll('#reading-content [data-block]')].map(node => { const r = node.getBoundingClientRect(); return [r.x,r.y,r.width,r.height]; }));
  await page.evaluate(() => document.fonts.ready); await page.waitForTimeout(250);
  assert.deepEqual(await articleStyles(), custom);
  await page.evaluate(() => { window.__colourArticle = document.querySelector('#reading-content'); window.__colourRuby = document.querySelector('#reading-content ruby'); });
  const before = await geometry();
  await trigger.click(); await rootSettings.locator('.favorite-apply').nth(1).click(); await save();
  await page.waitForFunction(id => !document.getElementById(id).open, dialogId);
  assert.equal((await articleStyles())[0], '#3D6D59');
  assert.deepEqual(await geometry(), before);
  assert.equal(await page.evaluate(() => window.__colourArticle === document.querySelector('#reading-content') && window.__colourRuby === document.querySelector('#reading-content ruby')), true);
  const ruby = page.locator('#reading-content ruby[data-lemma="solitude"]').first();
  await ruby.click();
  const knownBefore = await geometry();
  await page.locator('#mark-known').click();
  await page.waitForFunction(() => !document.querySelector('#word-card').open);
  assert.deepEqual(await geometry(), knownBefore);
  assert.equal(await ruby.locator('rt').evaluate(node => getComputedStyle(node).visibility), 'hidden');
  await page.locator('#next-page').click();
  await page.waitForTimeout(300);
  const later = page.locator('#reading-content ruby[data-lemma="murmur"]');
  const visible = await later.evaluateAll(nodes => nodes.findIndex(node => {
    const r = node.getBoundingClientRect(), viewport = document.querySelector('#reader-viewport').getBoundingClientRect();
    return r.left >= viewport.left && r.right <= viewport.right && r.top > viewport.top && r.bottom < viewport.bottom;
  }));
  assert(visible >= 0, 'later-page custom-colour word is visible');
  const point = await later.nth(visible).boundingBox();
  const laterBefore = await geometry();
  const laterPage = await page.locator('#reading-content').getAttribute('data-page');
  await page.mouse.click(point.x + point.width / 2, point.y + point.height / 2);
  await page.locator('#word-card[open]').waitFor();
  await page.locator('#mark-known').click();
  await page.waitForFunction(() => !document.querySelector('#word-card').open);
  assert.deepEqual(await geometry(), laterBefore);
  assert.equal(await page.locator('#reading-content').getAttribute('data-page'), laterPage);
  assert.equal(await later.nth(visible).locator('rt').evaluate(node => getComputedStyle(node).visibility), 'hidden');
  await page.locator('#previous-page').click();
  const durable = await preferences();
  await stop(); base = await start(); await page.goto(`${base}/settings`); await ready();
  assert.deepEqual(await preferences(), durable);
  assert.equal(await rootSettings.locator('.favorite-scheme').count(), 2);
  assert.deepEqual(errors, []);
  console.log('PASS: favorite apply is paint-only with unchanged reader/ruby/geometry; first/later-page known-word continuity and real server restart');
}
run().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  await browser?.close(); await stop(); fs.writeFileSync(path.join(artifacts, 'server.log'), log); fs.rmSync(temp, { recursive: true, force: true });
});
