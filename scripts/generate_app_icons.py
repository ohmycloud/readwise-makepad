#!/usr/bin/env python3
"""Build all ReadWise launcher icons from the two checked-in SVG masters.

Requires rsvg-convert and ImageMagick 7 (magick). No Python packages required.
Run from any directory; --check compares regenerated bytes without writing files.
"""
import argparse
import copy
import json
from pathlib import Path
import shutil
import struct
import subprocess
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
RES = Path('app/resources')
NS = '{http://www.w3.org/2000/svg}'
BG = '#F8DDD2'
SIZES = (16, 32, 64, 128, 256, 512, 1024)
DENSITIES = {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}


def master(small=False):
    return ET.parse(ROOT / RES / ('icon-small.svg' if small else 'icon.svg')).getroot()


def svg_bytes(tile='square', small=False, foreground=False):
    svg = copy.deepcopy(master(small))
    background = svg.find(f'{NS}rect')
    if foreground:
        svg.remove(background)
        # Android's guaranteed safe region is a central circle of diameter 66/108.
        # Scale around the optical centre so ears and horns fit inside it.
        svg.find(f'{NS}g').set('transform', 'translate(128 128) scale(0.74) translate(-128 -130)')
    elif tile == 'rounded':
        background.set('rx', '56')
    elif tile == 'circle':
        svg.remove(background)
        svg.insert(1, ET.Element(f'{NS}circle', {'cx': '128', 'cy': '128', 'r': '128', 'fill': BG}))
    return ET.tostring(svg, encoding='utf-8')


def render(svg, size, opaque=False):
    png = subprocess.run(['rsvg-convert', '-w', str(size), '-h', str(size)],
                         input=svg, stdout=subprocess.PIPE, check=True).stdout
    # Explicit PNG24 for iOS: no alpha channel, even an entirely opaque one.
    # Strip timestamps / profiles to make byte-for-byte regeneration stable.
    fmt = 'PNG24:-' if opaque else 'PNG32:-'
    return subprocess.run(['magick', 'png:-', '-strip', fmt], input=png,
                          stdout=subprocess.PIPE, check=True).stdout


def ico(images):
    sizes = sorted(images)
    offset = 6 + 16 * len(sizes)
    entries, data = [], []
    for size in sizes:
        png = images[size]
        entries.append(struct.pack('<BBBBHHII', size % 256, size % 256, 0, 0,
                                   1, 32, len(png), offset))
        data.append(png)
        offset += len(png)
    return struct.pack('<HHH', 0, 1, len(sizes)) + b''.join(entries + data)


def icns(images):
    types = {'icp4': 16, 'icp5': 32, 'icp6': 64, 'ic07': 128, 'ic08': 256,
             'ic09': 512, 'ic10': 1024, 'ic11': 32, 'ic12': 64, 'ic13': 256, 'ic14': 512}
    chunks = [key.encode() + struct.pack('>I', 8 + len(images[size])) + images[size]
              for key, size in types.items()]
    payload = b''.join(chunks)
    return b'icns' + struct.pack('>I', 8 + len(payload)) + payload


def json_bytes(value):
    return (json.dumps(value, indent=2) + '\n').encode()


def generate():
    for command in ('rsvg-convert', 'magick'):
        if not shutil.which(command):
            raise RuntimeError(f'{command} is required; install librsvg and ImageMagick.')
    assets = {}
    desktop = {size: render(svg_bytes('rounded', small=size <= 32), size)
               for size in sorted(set(SIZES) | {24, 48})}
    for size in SIZES:
        assets[RES / f'icon_{size}.png'] = desktop[size]
        # Workspace-level resource lookup is still used by some dev invocations.
        assets[Path('resources') / f'icon_{size}.png'] = desktop[size]
    assets[RES / 'icon.ico'] = ico({s: desktop[s] for s in (16, 24, 32, 48, 64, 128, 256)})
    assets[RES / 'icon.icns'] = icns(desktop)

    ios = Path('app/packaging/ios/icons/Assets.xcassets')
    info = {'version': 1, 'author': 'xcode'}
    assets[ios / 'Contents.json'] = json_bytes({'info': info})
    images = []
    for idiom, size, scales in [('iphone', n, (2, 3)) for n in (20, 29, 40, 60)] + [
            ('ipad', n, (1, 2)) for n in (20, 29, 40, 76)] + [('ipad', 83.5, (2,))]:
        for scale in scales:
            pixels = int(size * scale)
            name = f'AppIcon{pixels}x{pixels}.png'
            assets[ios / 'AppIcon.appiconset' / name] = render(svg_bytes(small=pixels <= 32), pixels, opaque=True)
            images.append({'idiom': idiom, 'size': f'{size}x{size}', 'scale': f'{scale}x', 'filename': name})
    name = 'AppIcon1024x1024.png'
    assets[ios / 'AppIcon.appiconset' / name] = render(svg_bytes(), 1024, opaque=True)
    images.append({'idiom': 'ios-marketing', 'size': '1024x1024', 'scale': '1x', 'filename': name})
    assets[ios / 'AppIcon.appiconset/Contents.json'] = json_bytes({'images': images, 'info': info})

    android = RES / 'android/res'
    for density, scale in DENSITIES.items():
        folder = android / f'mipmap-{density}'
        assets[folder / 'ic_launcher.png'] = render(svg_bytes('rounded'), int(48 * scale))
        assets[folder / 'ic_launcher_foreground.png'] = render(svg_bytes(foreground=True), int(108 * scale))
    assets[android / 'values/icon_colors.xml'] = (
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
        f'    <color name="ic_launcher_background">{BG}</color>\n</resources>\n').encode()
    assets[android / 'mipmap-anydpi-v26/ic_launcher.xml'] = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background"/>\n'
        '    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>\n'
        '</adaptive-icon>\n').encode()
    return assets


def preview():
    """A concise visual QA board; not embedded in the application's resources."""
    def embed(x, y, size, tile='rounded', small=False):
        svg = ET.fromstring(svg_bytes(tile, small))
        svg.set('x', str(x)); svg.set('y', str(y))
        svg.set('width', str(size)); svg.set('height', str(size))
        if tile == 'circle':
            # An adaptive 108dp layer is viewed through a central 72dp mask.
            svg.find(f'{NS}g').set('transform', 'translate(128 128) scale(1.11) translate(-128 -130)')
        return ET.tostring(svg, encoding='unicode')
    header = '<svg xmlns="http://www.w3.org/2000/svg" width="1100" height="660" viewBox="0 0 1100 660">'
    markup = header + '<rect width="1100" height="660" fill="#FFFAF7"/>'
    markup += '<g font-family="sans-serif" fill="#57332D"><text x="48" y="60" font-size="28">ReadWise / Terracotta giraffe</text>'
    for x, tile, label in [(48, 'rounded', 'Desktop'), (406, 'square', 'iOS / system mask'), (764, 'circle', 'Android / adaptive circle')]:
        markup += embed(x, 104, 256, tile)
        markup += f'<text x="{x}" y="396" font-size="18">{label}</text>'
    x = 48
    for size in (128, 64, 48, 32, 24, 16):
        markup += embed(x, 448 + 128 - size, size, small=size <= 32)
        markup += f'<text x="{x}" y="608" font-size="13">{size} px</text>'
        x += size + 36
    markup += '</g></svg>'
    return markup.encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Regenerate and compare; do not write')
    args = parser.parse_args()
    assets = generate()
    doc = Path('docs/design/giraffe-icon')
    assets[doc / 'final-preview.svg'] = preview()
    # Render the non-square board directly, preserving its 1100x660 aspect ratio.
    assets[doc / 'final-preview.png'] = subprocess.run(['rsvg-convert'], input=preview(),
                                                     stdout=subprocess.PIPE, check=True).stdout
    mismatches = [p for p, data in assets.items() if not (ROOT / p).is_file() or (ROOT / p).read_bytes() != data]
    if args.check:
        for path in mismatches:
            print(f'Stale or missing: {path}')
        if mismatches:
            raise SystemExit(1)
        print(f'All {len(assets)} generated icon assets match the SVG masters.')
    else:
        for path in mismatches:
            (ROOT / path).parent.mkdir(parents=True, exist_ok=True)
            (ROOT / path).write_bytes(assets[path])
        print(f'Updated {len(mismatches)} of {len(assets)} generated icon assets.')


if __name__ == '__main__':
    main()
